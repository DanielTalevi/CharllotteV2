-- CRIAR TABELAS:
-- Conecte-se ao banco "comissionesBB" e execute este arquivo
-- a partir do BEGIN.

BEGIN;

CREATE TABLE IF NOT EXISTS funcionario (
    id_funcionario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(250) NOT NULL,
    status BOOLEAN NOT NULL,
    online BOOLEAN NOT NULL,
    admin BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS produto (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    preco NUMERIC(12,2) NOT NULL,
    unidade VARCHAR(20) NOT NULL,
    percentual_comissao NUMERIC(5,2) NOT NULL,
    status BOOLEAN NOT NULL,
    quantidade_estoque NUMERIC(12,2) NOT NULL,
    estoque_minimo NUMERIC(12,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS aviso (
    id_aviso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    mensagem TEXT NOT NULL,
    data_criacao TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS venda (
    id_venda INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_funcionario INTEGER NOT NULL REFERENCES funcionario(id_funcionario),
    data_venda TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    valor_total NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('REALIZADA','EM_ANDAMENTO','CANCELADA'))
);

CREATE TABLE IF NOT EXISTS estoque (
    id_estoque INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto INTEGER NOT NULL UNIQUE REFERENCES produto(id_produto),
    quantidade NUMERIC(12,3) NOT NULL,
    estoque_minimo NUMERIC(12,3) NOT NULL,
    data_atualizacao TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS item_venda (
    id_item_venda INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venda INTEGER NOT NULL REFERENCES venda(id_venda),
    id_produto INTEGER NOT NULL REFERENCES produto(id_produto),
    quantidade NUMERIC(12,3) NOT NULL,
    preco_unitario NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS fraude (
    id_fraude INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venda INTEGER NOT NULL REFERENCES venda(id_venda),
    tipo VARCHAR(50) NOT NULL,
    descricao TEXT NOT NULL,
    data_identificacao TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('PENDENTE','EM_ANALISE','CONFIRMADA','DESCARTADA'))
);

CREATE TABLE IF NOT EXISTS mensagem (
    id_mensagem INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_funcionario INTEGER NOT NULL REFERENCES funcionario(id_funcionario),
    mensagem TEXT NOT NULL,
    data_envio TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS movimentacao_estoque (
    id_movimentacao_estoque INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto INTEGER NOT NULL REFERENCES produto(id_produto),
    id_funcionario INTEGER NOT NULL REFERENCES funcionario(id_funcionario),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA','AJUSTE')),
    quantidade NUMERIC(12,3) NOT NULL,
    data TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    motivo VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS comissao (
    id_comissao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venda INTEGER NOT NULL REFERENCES venda(id_venda),
    id_funcionario INTEGER NOT NULL REFERENCES funcionario(id_funcionario),
    percentual NUMERIC(5,2) NOT NULL,
    valor NUMERIC(12,2) NOT NULL,
    data TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS aviso_funcionario (
    id_aviso INTEGER NOT NULL REFERENCES aviso(id_aviso),
    id_funcionario INTEGER NOT NULL REFERENCES funcionario(id_funcionario),
    lido BOOLEAN NOT NULL,
    data_leitura TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_aviso_funcionario PRIMARY KEY (id_aviso, id_funcionario)
);

CREATE INDEX IF NOT EXISTS idx_venda_funcionario ON venda(id_funcionario);
CREATE INDEX IF NOT EXISTS idx_item_venda_venda ON item_venda(id_venda);
CREATE INDEX IF NOT EXISTS idx_item_venda_produto ON item_venda(id_produto);
CREATE INDEX IF NOT EXISTS idx_fraude_venda ON fraude(id_venda);
CREATE INDEX IF NOT EXISTS idx_mensagem_funcionario ON mensagem(id_funcionario);
CREATE INDEX IF NOT EXISTS idx_movimentacao_produto ON movimentacao_estoque(id_produto);
CREATE INDEX IF NOT EXISTS idx_movimentacao_funcionario ON movimentacao_estoque(id_funcionario);
CREATE INDEX IF NOT EXISTS idx_comissao_venda ON comissao(id_venda);
CREATE INDEX IF NOT EXISTS idx_comissao_funcionario ON comissao(id_funcionario);
CREATE INDEX IF NOT EXISTS idx_aviso_funcionario_funcionario ON aviso_funcionario(id_funcionario);

COMMIT;
